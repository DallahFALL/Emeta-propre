    function resolveTranslation(lang, key) {
        return translations[lang]?.[key] ?? translations.fr[key] ?? null;
    }

    function setLanguage(lang) {
        if (!Object.prototype.hasOwnProperty.call(translations, lang)) return false;
        document.documentElement.lang = lang;
        document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

        document.querySelectorAll("[data-i18n]").forEach((element) => {
            const value = resolveTranslation(lang, element.dataset.i18n);
            if (value !== null) element.innerHTML = value;
        });
        document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
            const value = resolveTranslation(lang, element.dataset.i18nPlaceholder);
            if (value !== null) element.setAttribute("placeholder", value);
        });
        document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
            const value = resolveTranslation(lang, element.dataset.i18nAriaLabel);
            if (value !== null) element.setAttribute("aria-label", value);
        });
        document.querySelectorAll("[data-i18n-content]").forEach((element) => {
            const value = resolveTranslation(lang, element.dataset.i18nContent);
            if (value !== null) element.setAttribute("content", value);
        });
        document.querySelectorAll(".lang-switch button").forEach((button) => {
            const selected = button.dataset.lang === lang;
            button.classList.toggle("active", selected);
            button.setAttribute("aria-pressed", String(selected));
        });
        document.querySelectorAll("[data-lang-link]").forEach((link) => {
            const target = new URL(link.href, window.location.href);
            target.searchParams.set("lang", lang);
            link.href = target.href;
        });
        try {
            localStorage.setItem("emeta_lang", lang);
        } catch (error) {
            console.warn("La préférence de langue ne peut pas être mémorisée.", error);
        }
        window.dispatchEvent(new CustomEvent("emeta:languagechange", { detail: { lang } }));
        return true;
    }

    window.EMETA_I18N = Object.freeze({ translations, sectors, sectorDetails, resolveTranslation });
