function setLanguage(lang) {
    if (!Object.prototype.hasOwnProperty.call(translations, lang)) lang = 'fr';
    
    document.documentElement.lang = lang;
    document.documentElement.dir = (lang === 'ar') ? 'rtl' : 'ltr';
    document.documentElement.setAttribute('translate', 'yes');
    
    localStorage.setItem('emeta_lang', lang);

    ['fr', 'en', 'es', 'ar'].forEach(l => {
        const btn = document.getElementById('lang' + l.toUpperCase());
        if (btn) {
            btn.className = (l === lang) ? 'underline font-bold text-gold' : 'hover:underline text-slate-400';
        }
    });

    const dictionary = translations[lang];
    const elements = document.querySelectorAll(
        '[data-i18n], [data-i18n-placeholder], [data-i18n-content], [data-i18n-title], [data-i18n-aria-label]'
    );
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (key && Object.prototype.hasOwnProperty.call(dictionary, key)) {
            const value = dictionary[key];
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = value;
            } else if (el.tagName === 'OPTGROUP') {
                el.label = value;
            } else if (el.hasAttribute('data-i18n-rich-text')) {
                el.innerHTML = value;
            } else {
                const textWalker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT, {
                    acceptNode(node) {
                        const parent = node.parentElement;
                        if (!parent || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
                        if (parent.closest('script, style, svg, i, [aria-hidden="true"]')) {
                            return NodeFilter.FILTER_REJECT;
                        }
                        return NodeFilter.FILTER_ACCEPT;
                    }
                });
                const textNode = textWalker.nextNode();
                if (textNode) {
                    textNode.nodeValue = value;
                } else {
                    el.textContent = value;
                }
            }
        }

        ['placeholder', 'content', 'title', 'aria-label'].forEach(attribute => {
            const attributeKey = el.getAttribute(`data-i18n-${attribute}`);
            if (attributeKey && Object.prototype.hasOwnProperty.call(dictionary, attributeKey)) {
                el.setAttribute(attribute, dictionary[attributeKey]);
            }
        });
    });

    document.querySelectorAll('a[href*=".html"]').forEach(link => {
        const href = link.getAttribute('href');
        if (href && /\.html(?:[?#]|$)/i.test(href) && !href.startsWith('http') && !href.startsWith('#')) {
            const target = new URL(href, window.location.href);
            target.searchParams.set('lang', lang);
            const relativePath = href.split(/[?#]/)[0];
            link.href = relativePath + target.search + target.hash;
        }
    });

    const currentUrl = new URL(window.location.href);
    currentUrl.searchParams.set('lang', lang);
    window.history.replaceState(window.history.state, '', currentUrl);

    window.dispatchEvent(new CustomEvent('emeta:languagechange', { detail: { lang } }));
}

window.i18n = {
    setLanguage,
    translate(key) {
        const lang = document.documentElement.lang || 'fr';
        return translations[lang]?.[key] ?? translations.fr[key] ?? key;
    }
};

window.setLang = function(lang) {
    setLanguage(lang);
};

window.setCurrency = function(curr) {
    localStorage.setItem('emeta_currency', curr);

    ['EUR', 'USD', 'XOF'].forEach(c => {
        const btn = document.getElementById('curr' + c);
        if (btn) {
            btn.className = (c === curr) ? 'underline font-bold text-gold' : 'hover:underline text-slate-400';
        }
    });

    document.querySelectorAll('.price-tag').forEach(el => {
        if (curr === 'EUR' && el.dataset.eur) el.innerHTML = el.dataset.eur;
        if (curr === 'USD' && el.dataset.usd) el.innerHTML = el.dataset.usd;
        if (curr === 'XOF' && el.dataset.xof) el.innerHTML = el.dataset.xof;
    });
};

window.addEventListener('DOMContentLoaded', () => {
    const urlParams = new URLSearchParams(window.location.search);
    const activeLang = urlParams.get('lang') || localStorage.getItem('emeta_lang') || 'fr';
    setLanguage(activeLang);

    const activeCurrency = localStorage.getItem('emeta_currency') || 'EUR';
    setCurrency(activeCurrency);
});
